export async function samplePullRequest(id: string): Promise<PullRequestDetail> {
  const pr = pullRequests.find((item) => item.id === id);
  if (!pr) throw new Error("Unknown sample pull request");
  return {
    ok: true,
    pullRequest: {
      id: pr.id,
      number: pr.number,
      title: pr.title,
      author: pr.author,
      url: pr.url,
      state: pr.state,
      draft: pr.draft,
      headSha: pr.headSha,
      baseSha: sha("f0"),
      openedAt: pr.openedAt,
      repository: pr.repository,
    },
    runs: runs.filter((item) => item.prId === id),
    findings: findings.filter((item) => item.prId === id),
  };
}
